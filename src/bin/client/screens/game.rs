//! Координатор жизненного цикла окна игры.
//!
//! Этот модуль — узкая точка сборки запущенной игры. Он владеет двумя уже
//! разделёнными компонентами:
//!
//! - [`GameEngine`] владеет запущенными правилами и состоянием мира;
//! - [`GameUi`] владеет физическим вводом, визуальным состоянием, отрисовкой и
//!   анимацией.
//!
//! Оба компонента получают готовые контексты от менеджера ресурсов. Само окно не
//! открывает файлы сценария, не загружает изображения или шрифты, не разбирает
//! нажатия по карте, не выполняет правила, не строит элементы интерфейса и ничего
//! не рисует.
//!
//! В каждом кадре данные идут строго по одной цепочке:
//!
//! `GameUi::frame -> Vec<GameEvent> -> GameEngine::process -> Vec<Delivery>
//!  -> GameUi::apply`
//!
//! Полный снимок запрашивается только тогда, когда интерфейс сообщает, что одних
//! пришедших изменений недостаточно для безопасного обновления. Единственное
//! событие, которое окно обрабатывает самостоятельно, — Escape. Выход из игры
//! относится к переходам между окнами приложения, а не к игровым правилам или
//! внутренней логике интерфейса.

use macroquad::prelude::{KeyCode, is_key_pressed};

use crate::{
    game_engine::GameEngine,
    game_ui::GameUi,
    resource_loader::GameContext,
};

/// Действия для оболочки приложения, а не для игрового движка.
pub enum Action {
    None,
    ExitToMenu,
}

/// Владеет временем жизни одного окна игры и обменом сообщениями внутри него.
///
/// Здесь не должно быть состояния отрисовки или игровых правил. Если хочется
/// добавить в эту структуру ещё одно поле, скорее всего оно должно находиться в
/// `GameEngine`, `GameUi` или менеджере ресурсов.
pub struct GameScreen {
    engine: GameEngine,
    ui: GameUi,
}

impl GameScreen {
    /// Запускает обе части игры из контекстов выбранного приключения.
    ///
    /// Разделение `GameContext` здесь — только передача владения. Подробности
    /// инициализации остаются внутри соответствующих компонентов. Если интерфейс
    /// не удалось запустить, ошибка вернётся до перехода приложения в окно игры.
    pub fn new(context: GameContext) -> Result<Self, String> {
        Ok(Self {
            engine: GameEngine::start(context.engine),
            ui: GameUi::start(context.interface)?,
        })
    }

    /// Выполняет один кадр запущенной игры.
    ///
    /// Метод только координирует границы компонентов:
    ///
    /// 1. интерфейс читает ввод и превращает его в игровые события;
    /// 2. полученные смысловые события передаются движку;
    /// 3. сообщения движка передаются обратно интерфейсу;
    /// 4. если интерфейс просит, у движка запрашивается полный снимок мира.
    ///
    /// Метод возвращает в `client.rs` действие перехода между окнами, но сам этот
    /// переход не выполняет.
    pub fn draw(&mut self) -> Action {
        if is_key_pressed(KeyCode::Escape) {
            return Action::ExitToMenu;
        }

        let events = self.ui.frame();
        let deliveries = self.engine.process(events);
        if self.ui.apply(deliveries) {
            self.ui.apply(self.engine.snapshot());
        }
        Action::None
    }
}
